#!/usr/bin/env python3
"""Generate src/font_data.h: an 8-bit alpha glyph atlas for printable ASCII.

Usage: python3 tools/genfont.py path/to/DejaVuSansMono-Bold.ttf src/font_data.h
DejaVu fonts are under the Bitstream Vera / DejaVu license (free to embed).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

ttf, out = sys.argv[1], sys.argv[2]
SIZE = 20
font = ImageFont.truetype(ttf, SIZE)
asc, desc = font.getmetrics()
CW = int(round(font.getlength("M")))
CH = asc + desc
FIRST, LAST = 32, 126
n = LAST - FIRST + 1

atlas = Image.new("L", (CW * n, CH), 0)
d = ImageDraw.Draw(atlas)
for i, c in enumerate(range(FIRST, LAST + 1)):
    d.text((i * CW, 0), chr(c), font=font, fill=255)

px = atlas.tobytes()
with open(out, "w") as f:
    f.write("/* generated by tools/genfont.py from DejaVu Sans Mono Bold */\n")
    f.write("#pragma once\n")
    f.write(f"#define FONT_CW {CW}\n#define FONT_CH {CH}\n")
    f.write(f"#define FONT_FIRST {FIRST}\n#define FONT_COUNT {n}\n")
    f.write(f"#define FONT_ATLAS_W {CW * n}\n")
    f.write("static const unsigned char font_atlas[] = {\n")
    for i in range(0, len(px), 32):
        f.write(",".join(str(b) for b in px[i:i + 32]) + ",\n")
    f.write("};\n")
print(f"cell {CW}x{CH}, atlas {CW*n}x{CH}")
